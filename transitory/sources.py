"""Where light curves come from.

The pipeline only talks to a :class:`LightCurveSource`.  ``SyntheticSource``
(here) serves made-up data for tests and ``--demo``; ``MastSource`` in
``pipeline/fetch.py`` downloads real TESS / Kepler data.
"""

from __future__ import annotations

import zlib
from typing import Protocol, runtime_checkable

from .models import KnownPlanet, LightCurve, ProgressCallback, StarTarget
from .synthetic import SyntheticStar, demo_stars, make_light_curve


class SourceError(RuntimeError):
    """A source could not provide data for a target (not found, no coverage, offline)."""


@runtime_checkable
class LightCurveSource(Protocol):
    name: str

    def fetch(self, target: StarTarget, progress_cb: ProgressCallback | None = None) -> LightCurve:
        """Return the stitched light curve for ``target``; raise SourceError if none."""
        ...

    def credits(self, lc: LightCurve) -> list[str]:
        """Acknowledgement lines required for the data in ``lc``."""
        ...


SYNTHETIC_CREDIT = "Synthetic light curve generated by transitory (demo / test data; not real observations)."


class SyntheticSource:
    """Serves made-up light curves; no network.

    Known stars are matched by name (case-insensitive) or TIC/KIC.  With
    ``allow_unknown`` any other target gets a deterministic planet-free curve,
    so the demo dashboard accepts whatever the user types.
    """

    name = "Synthetic"

    def __init__(self, stars: list[SyntheticStar] | None = None, allow_unknown: bool = True):
        self.stars = list(demo_stars() if stars is None else stars)
        self.allow_unknown = allow_unknown

    def find(self, target: StarTarget) -> SyntheticStar | None:
        key = target.name.strip().lower()
        for star in self.stars:
            t = star.target
            if t.name.lower() == key:
                return star
            if target.tic is not None and t.tic == target.tic:
                return star
            if target.kic is not None and t.kic == target.kic:
                return star
        return None

    def fetch(self, target: StarTarget, progress_cb: ProgressCallback | None = None) -> LightCurve:
        if progress_cb:
            progress_cb(f"Generating synthetic data for {target.name}", 0.0)
        star = self.find(target)
        if star is None:
            if not self.allow_unknown:
                raise SourceError(f"No synthetic data for {target.name!r}")
            star = SyntheticStar(target=target, planets=[],
                                 seed=zlib.crc32(target.name.encode("utf-8")))
        lc = make_light_curve(star)
        if progress_cb:
            progress_cb(f"Synthetic data ready for {target.name}", 1.0)
        return lc

    def credits(self, lc: LightCurve) -> list[str]:
        return [SYNTHETIC_CREDIT]

    def targets(self) -> list[StarTarget]:
        return [s.target for s in self.stars]

    def known_planets(self, target: StarTarget) -> list[KnownPlanet]:
        star = self.find(target)
        return [p.as_known() for p in star.planets] if star else []
